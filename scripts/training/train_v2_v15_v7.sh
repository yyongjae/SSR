#!/usr/bin/env bash
# v2_v15_v7 (report 132): baseline v2-seg + BEV selector v15 (km 64 m port) + refiner v2 on the front 0-64 m,
# 100 x 100 BEV, with lens undistortion and camera pillars at z [-1, 3].  Thin wrapper around the CK2 e2e launcher
# (tools/ck/e2e2/train_e2e2.sh: training + CPU labeler + watchdog, same recipe as byounggun's fusion_v15_main):
#   - CK_BEV64=1 for every process it starts (refiner S grid / teacher caches 100 x 100; ck_e2e2 refuses a mismatch
#     between this and the BEV config);
#   - E2E_EXTRA = tools/ck/e2e2/v2_v15_v7_arm.extra (grid, seg head, v15) preceded by the v15 probe schedule for the
#     GPU count (warm-up 1.0 / ramp 0.5 epoch in per-rank micro-batches: 21200 / 10600 over ngpu, = 5300 / 2650 on 4
#     GPUs as fusion_v15_main, 2650 / 1325 on 8); a caller's E2E_EXTRA replaces the arm file and may override these;
#   - E2E_CK_SET = tools/ck/e2e2/v2_v15_v7.set (refiner teachers + KD calibration);
#   - GPUs 4-7 (CK_ALLOW_GPU4567=1) only when listed in --gpus (user 2026-11-02: student on 0-7); the launcher keeps the
#     global batch 128 (4 per GPU x ngpu x accumulate) and rescales its per-rank counters;
#   - outputs under $E2E_ROOT/<RUN>, default $SSR_RUN_ROOT (never under another user's tree, train_e2e2.sh refuses).
#
#   RUN=v2_v15_v7_main CK2_E2E_APPROVED=1 bash scripts/training/train_v2_v15_v7.sh start --gpus 0,1,2,3,4,5,6,7
#   RUN=v2_v15_v7_main bash scripts/training/train_v2_v15_v7.sh status | stop | wait
#   RUN=v2_v15_v7_main E2E_DRY_RUN=1 CK2_E2E_APPROVED=1 bash scripts/training/train_v2_v15_v7.sh start --gpus 0,1,2,3
#   smoke: RUN=<name> E2E_SMOKE=1 E2E_ROOT=$SSR_DATA_ROOT/ck/ck2/e2e_smoke ... (launcher rules)
set -euo pipefail
REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd -P)"
source "$REPO/tools/release/load_paths.sh"   # SSR_PY, SSR_DATA_ROOT, SSR_RUN_ROOT, ... (navsim/common/ssr_paths.py)
export CK_BEV64=1 SSR_ALLOW_DIRECT=1
export E2E_ROOT=${E2E_ROOT:-$SSR_RUN_ROOT}
export E2E_CK_SET=${E2E_CK_SET:-$REPO/tools/ck/e2e2/v2_v15_v7.set}
SRC_EXTRA=${E2E_EXTRA:-$REPO/tools/ck/e2e2/v2_v15_v7_arm.extra}

GPUS=""; prev=""
for a in "$@"; do [ "$prev" = "--gpus" ] && GPUS=$a; prev=$a; done
if [ -n "$GPUS" ]; then
  NG=$(echo "$GPUS" | tr ',' '\n' | grep -c .)
  case ",$GPUS," in *,4,*|*,5,*|*,6,*|*,7,*) export CK_ALLOW_GPU4567=1;; esac
  if [ $((21200 % NG)) -ne 0 ]; then echo "[train_v2_v15_v7] unsupported GPU count $NG" >&2; exit 2; fi
  mkdir -p "$E2E_ROOT/_extra"
  X="$E2E_ROOT/_extra/${RUN:?RUN=<run name> is required}.extra"
  {
    echo "# generated by scripts/training/train_v2_v15_v7.sh for $NG GPUs ($GPUS); source $SRC_EXTRA"
    echo "++agent.config.distill_probe_warmup_steps=$((21200 / NG))"
    echo "++agent.config.distill_probe_ramp_steps=$((10600 / NG))"
    cat "$SRC_EXTRA"
  } > "$X"
  export E2E_EXTRA=$X
else
  export E2E_EXTRA=$SRC_EXTRA
fi
exec bash "$REPO/tools/ck/e2e2/train_e2e2.sh" "$@"
