    o, ck, teachers = ov("kd_calib.det=null", f"kd_calib.map={pM}", name="ck2e2e_maponly")
    assert teachers["kd_calib"]["det"] is None and teachers["kd_calib"]["map"]["path"] == str(pM)
    # teacher_check itself (kd_calib given) and the teacher-check CLI flags (exit 3 = refused)
    T, M = str(TL.SMOKE_T), str(TL.SMOKE_M)
    rec = L2.teacher_check(T, M, mode="smoke", deep=False, ep_target="official",
                           kd_calib={"enabled": True, "det": str(pT), "map": str(pM)})
    assert rec["kd_calib"]["det"]["sha16"] == KC.file_sha16(pT) and rec["kd_calib"]["map"]["arm"] == "M"
    with pytest.raises(L2.LaunchError, match="fit_kd_calib.py"):
        L2.teacher_check(T, M, mode="smoke", deep=False, ep_target="official",
                         kd_calib={"enabled": True, "det": str(missing), "map": None})
    assert "kd_calib" not in L2.teacher_check(T, M, mode="smoke", deep=False, ep_target="official")
    cli = ["teacher-check", "--det", T, "--map", M, "--mode", "smoke", "--ep-target", "official"]
