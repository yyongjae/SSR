@need_inputs
def test_fit_tool_forward_equals_teacher_pair_and_fit_all():
    from navsim.agents.para_ssr.ck.model import load_ck
    from tools.ck.e2e2 import fit_kd_calib as F
    pair = O.TeacherPair2(str(TL.SMOKE_T), str(TL.SMOKE_M), "last", "cpu", amp=False)
    f, t = TL.fresh(2)
    cand = _cands(t, 9, seed=7)
    out = pair.run(t["kd_bev_0"], t["kd_ok_0"], t["kd_bev_1"], t["kd_ok_1"], cand, f["status_feature"])
    for run, tnet, bev, key in ((TL.SMOKE_T, pair.det, t["kd_bev_0"], "p_det"),
                                (TL.SMOKE_M, pair.map, t["kd_bev_1"], "p_map")):
        s = F.teacher_logits(tnet, bev, cand, f["status_feature"], amp=True)         # amp only acts on CUDA
        assert torch.equal(torch.sigmoid(s), out[key])                              # same net: bitwise
        net, _ = load_ck(run, "last")                                                # the tool's own load_ck
        s2 = F.teacher_logits(net, bev, cand, f["status_feature"], amp=True)
        torch.testing.assert_close(s2, s, rtol=1e-5, atol=1e-5)
    # fit_all: fitted keys of the arm only, identity elsewhere; known parameters recovered
    rng = np.random.default_rng(0)
    Tn, K = 3000, 16
    z = rng.normal(0, 2, (Tn, K, 5)).astype(np.float32)
    true = {"nc": (0.6, 1.0), "dac": (1.4, -0.5), "ep": (0.8, 0.6), "ttc": (0.5, 1.5), "comfort": (1.0, 0.0)}
    y = np.stack([(rng.random((Tn, K)) < _sig(true[k][0] * z[..., j] + true[k][1])).astype(np.float32)
                  for j, k in enumerate(CK_KEYS)], -1)
    ok = rng.random((Tn, K)) > 0.05
    folds = KC.log_folds(np.asarray([f"l{i % 97}" for i in range(Tn)]), 0)
    R = F.fit_all(z, y, ok, folds, "M", ["nc", "dac", "ep", "ttc"])
    assert set(R["params"]) == {"dac", "ep"} and R["fitted_keys"] == ["dac", "ep"]
    for k in ("dac", "ep"):
        assert abs(R["params"][k]["a"] - true[k][0]) < 0.05 and abs(R["params"][k]["b"] - true[k][1]) < 0.05
        h = R["metrics"][k]["heldout"]
        assert h["after"]["nll"] < h["before"]["nll"]
    assert R["metrics"]["nc"]["status"] == "not_fitted" and "heldout" not in R["metrics"]["nc"]
    assert R["metrics"]["dac"]["n"] == int(ok.sum())
