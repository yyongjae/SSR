    assert kc["enabled"] and kc["det"]["sha16"] == KC.file_sha16(pT) and kc["map"]["sha16"] == KC.file_sha16(pM)
    assert kc["det"]["ckpt_sha16"] == teachers["det"]["ckpt_sha16"] and kc["map"]["fitted_keys"] == ["dac", "ep"]
    assert f"++agent.config.ck_e2e2.kd_calib.det={pT}" in o and "++agent.config.ck_e2e2.kd_calib.enabled=true" in o
