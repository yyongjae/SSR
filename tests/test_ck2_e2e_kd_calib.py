def _sig(x):
    return 1.0 / (1.0 + np.exp(-x))


def _synth(n, a, b, seed, soft=False, scale=2.0):
    rng = np.random.default_rng(seed)
    z = rng.normal(0.0, scale, n)
    p = _sig(a * z + b)
    y = p if soft else (rng.random(n) < p).astype(np.float64)
    return z, y


# ----------------------------------------------------------------------------------------------- numerics
def test_platt_fit_recovers_known_params():
    z, y = _synth(300_000, 0.6, 0.8, 0)
    r = KC.fit_platt(z, y)
    assert r["converged"] and not r["at_bound"]
    assert abs(r["a"] - 0.6) < 0.02 and abs(r["b"] - 0.8) < 0.02
    z, y = _synth(50_000, 1.7, -1.2, 1, soft=True)                      # soft targets = the true probabilities
    r = KC.fit_platt(z, y)
    assert abs(r["a"] - 1.7) < 1e-3 and abs(r["b"] + 1.2) < 1e-3
    # the optimum: zero gradient of the data term (up to the tiny ridge)
    p = _sig(r["a"] * z + r["b"])
    assert abs(np.mean((p - y) * z)) < 1e-5 and abs(np.mean(p - y)) < 1e-5
    # NC-like 0.5 labels are soft targets (no error), labels outside [0, 1] are refused
    KC.fit_platt(np.array([0.0, 1.0, 2.0, -1.0]), np.array([0.5, 1.0, 1.0, 0.0]))
    with pytest.raises(ValueError, match="0, 1"):
        KC.fit_platt(np.array([0.0, 1.0]), np.array([0.0, 1.5]))
    # an anti-correlated teacher: a stays > 0 (at the bound), the bias absorbs the mean
    z, y = _synth(20_000, -1.0, 0.0, 2)
    r = KC.fit_platt(z, y)
    assert r["at_bound"] and r["a"] == KC.A_MIN and abs(_sig(r["b"]) - y.mean()) < 0.02


@pytest.mark.parametrize("seed,a,b", [(0, 0.5, 1.5), (1, 1.6, -0.7), (2, 0.8, 3.0), (3, 2.0, 0.4), (4, 0.3, 2.5)])
def test_heldout_never_worse_than_identity_well_specified(seed, a, b):
    """data generated by a miscalibrated teacher (y ~ Bernoulli(sigmoid(a z + b))): the out-of-fold Platt NLL on the
    held-out logs is below the raw teacher's (identity) NLL, ECE drops, the mean prediction matches the labels."""
    rng = np.random.default_rng(100 + seed)
    n_tok, k = 4000, 16
    logs = np.asarray([f"log{i}" for i in rng.integers(0, 300, n_tok)])
    z, y = _synth(n_tok * k, a, b, seed)
    fold = np.repeat(KC.log_folds(logs, seed), k)
    h = KC.heldout_2fold(z, y, fold)
    assert h["after"]["nll"] < h["before"]["nll"]
    assert h["after"]["ece"] < h["before"]["ece"] and h["after"]["ece"] < 0.02
    assert abs(h["after"]["mean_pred"] - h["after"]["mean_label"]) < 0.01
    for f in h["folds"]:
        assert f["nll_after"] <= f["nll_before"]
    # an already calibrated teacher (identity is the truth): the held-out fit costs at most estimation noise
    z, y = _synth(n_tok * k, 1.0, 0.0, seed + 50)
    h = KC.heldout_2fold(z, y, fold)
    assert h["after"]["nll"] <= h["before"]["nll"] + 2e-4


def test_log_folds_and_metrics():
    logs = np.asarray(["a", "a", "b", "c", "c", "d", "e"])
    f = KC.log_folds(logs, 0)
    assert set(f.tolist()) == {0, 1}
    for lg in np.unique(logs):                                           # a log never straddles the split
        assert len(set(f[logs == lg].tolist())) == 1
    assert (KC.log_folds(logs, 0) == f).all()
    assert KC.heldout_2fold(np.zeros(4), np.ones(4), np.zeros(4))["skipped"]
    z, y = _synth(200_000, 1.0, 0.0, 9)
    p = _sig(z)
    assert KC.ece(p, y) < 0.01 and KC.ece(p, y, mode="mass") < 0.01
    assert KC.ece(np.full(10, 0.9), np.zeros(10)) == pytest.approx(0.9)
    assert KC.bce_logit(z, y) == pytest.approx(float(np.mean(-(y * np.log(p) + (1 - y) * np.log(1 - p)))), rel=1e-6)
    assert KC.nll_const(np.array([1.0, 1.0, 0.0, 0.0])) == pytest.approx(np.log(2))
    assert KC.fit_keys("T") == ["nc", "ep", "ttc"] and KC.fit_keys("M") == ["dac", "ep"]
    assert KC.fit_keys("T", ["nc", "dac", "ep", "ttc", "comfort"]) == ["nc", "ep", "ttc", "comfort"]


def test_apply_platt_identity_bitwise_and_values():
    x = torch.randn(3, 7, 5) * 4
    x[0, 0, 0] = float("nan")
    a = np.ones(5, np.float32)
    b = np.zeros(5, np.float32)
    y = KC.apply_platt(x, a, b)
    assert torch.equal(torch.nan_to_num(y, 123.0), torch.nan_to_num(x, 123.0))
    a[1], b[1] = 0.5, 2.0
    y = KC.apply_platt(x, a, b)
    torch.testing.assert_close(y[..., 1], 0.5 * x[..., 1] + 2.0, rtol=0, atol=0)
    assert torch.equal(y[..., 2], x[..., 2])
    yn = KC.apply_platt(x.numpy(), a, b)
    assert yn.dtype == np.float32 and np.allclose(yn[..., 1], 0.5 * x.numpy()[..., 1] + 2.0)


