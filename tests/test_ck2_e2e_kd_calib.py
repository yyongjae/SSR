def test_student_loss_only_the_score_kd_term_changes(tmp_path):
    """CKE2E2.loss (warm-up step): kd_calib off == identity files bit for bit (loss and every log); with real
    calibration only the score-KD term moves (label BCE, surrogate, lateral KD unchanged bitwise) and the KD target the
    loss sees is the calibrated combination."""
    T, M = TL.SMOKE_T, TL.SMOKE_M
    files = {"id": (_write(tmp_path, "iT.json", T, "T", {k: {"a": 1.0, "b": 0.0} for k in KC.fit_keys("T")}),
                    _write(tmp_path, "iM.json", M, "M", {k: {"a": 1.0, "b": 0.0} for k in KC.fit_keys("M")})),
             "cal": (_write(tmp_path, "T.json", T, "T", P_DET), _write(tmp_path, "M.json", M, "M", P_MAP))}
    res = {}
    for name in ("off", "id", "cal"):
        kc = {"enabled": False} if name == "off" else {"enabled": True, "det": str(files[name][0]),
                                                       "map": str(files[name][1])}
        c = TL.cfg2(tmp_path / name, kd_calib=kc, ep_target="official", teacher_ep_check=True)
        ck = O.CKE2E2(c)
        torch.manual_seed(0)
        st = O.build_student_ck2(c)
        tp = ck.teachers(torch.device("cpu"))
        seen = {}
        run = tp.run
        tp.run = lambda *a, **k: seen.setdefault("T", run(*a, **k))
        f, t = TL.fresh(2)
        loss, logs = ck.loss(st, f, t, TL.fake_predictions(2, seed=0))
        res[name] = (loss.detach(), {k: float(v) for k, v in logs.items() if not k.endswith("_ms")}, seen["T"])
    assert torch.equal(res["off"][0], res["id"][0]) and res["off"][1] == res["id"][1]
    lo, lc = res["off"][1], res["cal"][1]
    for k in ("ck2/bce", "ck2/sur", "ck2/lat_kd", "ck2/e_abs_T"):
        assert lo[k] == lc[k], k
    assert lo["ck2/kd_score"] != lc["ck2/kd_score"] and not torch.equal(res["off"][0], res["cal"][0])
    Tc = res["cal"][2]
    pd_, pm = Tc["p_det"], Tc["p_map"]
    want = torch.stack([pd_[..., 0], pm[..., 1], 0.5 * (pd_[..., 2] + pm[..., 2]), pd_[..., 3],
                        0.5 * (pd_[..., 4] + pm[..., 4])], -1)
    torch.testing.assert_close(Tc["kd_score_prob"], want, rtol=0, atol=1e-7)
    j = CK_KEYS.index("dac")
    assert not torch.equal(Tc["kd_score_prob"][..., j], res["off"][2]["kd_score_prob"][..., j])


