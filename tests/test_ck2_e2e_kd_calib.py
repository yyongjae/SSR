def _ckpt_sha(run: Path) -> str:
    from tools.ck import ckutil as U
    return U.sha256_file(run / "ckpt_last.pt")


def _write(tmp: Path, name: str, run: Path, arm: str, params, **over) -> Path:
    kw = dict(run=str(run), which="last", arm=arm, ckpt=str(run / "ckpt_last.pt"), ckpt_sha16=_ckpt_sha(run),
              ep_target="official", params=params, created="test")
    kw.update(over)
    rec = KC.build_record(**kw)
    p = Path(tmp) / name
    p.write_text(json.dumps(rec))
    return p


@need_inputs
def test_record_roundtrip_and_refusals(tmp_path):
    T, M = TL.SMOKE_T, TL.SMOKE_M
    pT = _write(tmp_path, "T.json", T, "T", P_DET)
    a, b, info = KC.load_teacher_calib(pT, run=str(T), which="last", ckpt_sha16=_ckpt_sha(T), ep_target="official",
                                       arm="T")
    assert a.dtype == np.float32 and a.shape == (5,)
    want_a = [P_DET.get(k, {"a": 1.0})["a"] for k in CK_KEYS]
    want_b = [P_DET.get(k, {"b": 0.0})["b"] for k in CK_KEYS]
    assert np.allclose(a, want_a) and np.allclose(b, want_b)
    rec = KC.load_calib(pT)
    assert rec["fitted_keys"] == ["nc", "ep", "ttc"] and rec["params"]["dac"] == {"a": 1.0, "b": 0.0,
                                                                                    "status": "not_fitted"}
    assert info["sha16"] == KC.file_sha16(pT) and info["ckpt_sha16"] == _ckpt_sha(T)
    # json round trip: the reloaded record re-validates and builds the same vectors
    assert KC.calib_vectors(json.loads(json.dumps(rec)))[0].tolist() == a.tolist()
    ok = dict(run=str(T), which="last", ckpt_sha16=_ckpt_sha(T), ep_target="official", arm="T")
    for over, msg in (({"ckpt_sha16": "0" * 16}, "ckpt sha16"), ({"ep_target": "decoupled"}, "ep_target"),
                      ({"which": "ep0"}, "which"), ({"run": str(M)}, "run"), ({"arm": "M"}, "arm"),
                      ({"ckpt_sha16": None}, "ckpt sha16")):
        with pytest.raises(ValueError, match=msg):
            KC.load_teacher_calib(pT, **dict(ok, **over))
    # a file without one of the teacher's KD keys (EP not fitted) is refused for the default KD keys
    pT2 = _write(tmp_path, "T_noep.json", T, "T", {k: v for k, v in P_DET.items() if k != "ep"},
                 kd_keys=["nc", "dac", "ttc"])
    with pytest.raises(ValueError, match=r"\['ep'\].*not fitted"):
        KC.load_teacher_calib(pT2, **ok)
    KC.load_teacher_calib(pT2, kd_keys=["nc", "dac", "ttc"], **ok)        # fine when EP is not distilled
    # malformed records
    with pytest.raises(ValueError, match="not KD keys"):
        _write(tmp_path, "x.json", T, "T", dict(P_DET, dac={"a": 1.0, "b": 0.1}))
    with pytest.raises(ValueError, match="no params"):
        _write(tmp_path, "x.json", T, "T", {"nc": {"a": 1.0, "b": 0.0}})
    with pytest.raises(ValueError, match="a > 0"):
        _write(tmp_path, "x.json", T, "T", dict(P_DET, nc={"a": 0.0, "b": 0.0}))
    bad = json.loads(pT.read_text())
    bad["params"]["dac"]["b"] = 0.2                                         # 'not_fitted' must be the identity
    (tmp_path / "bad.json").write_text(json.dumps(bad))
    with pytest.raises(ValueError, match="identity"):
        KC.load_calib(tmp_path / "bad.json")
    with pytest.raises(FileNotFoundError):
        KC.load_calib(tmp_path / "missing.json")


