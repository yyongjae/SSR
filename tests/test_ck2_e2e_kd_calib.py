def _cands(t, n=10, seed=0):
    g = torch.Generator().manual_seed(seed)
    a = torch.from_numpy(np.load(TL.ANCHORS)).float()
    idx = torch.randint(0, 256, (t["ck2_gt"].shape[0], n), generator=g)
    return a[idx] + 0.05 * torch.randn(idx.shape + (8, 3), generator=g)


def _raw_logits(net, bev, cand, status):
    with torch.no_grad():
        return net(bev.float(), cand, status.float(), decode=False)["score_logit"].float()


@need_inputs
def test_teacher_pair_kd_target_is_calibrated_then_combined(tmp_path):
    T, M = TL.SMOKE_T, TL.SMOKE_M
    pT = _write(tmp_path, "T.json", T, "T", P_DET)
    pM = _write(tmp_path, "M.json", M, "M", P_MAP)
    raw = O.TeacherPair2(str(T), str(M), "last", "cpu", amp=False)
    cal = O.TeacherPair2(str(T), str(M), "last", "cpu", amp=False, calib={"det": str(pT), "map": str(pM)},
                         kd_keys=["nc", "dac", "ep", "ttc"])
    assert set(cal.calib) == {"det", "map"} and cal.calib_info["det"]["fitted_keys"] == ["nc", "ep", "ttc"]
    f, t = TL.fresh(2)
    cand = _cands(t)
    args = (t["kd_bev_0"], t["kd_ok_0"], t["kd_bev_1"], t["kd_ok_1"], cand, f["status_feature"])
    o_raw, o_cal = raw.run(*args), cal.run(*args)
    z_det = _raw_logits(cal.det, t["kd_bev_0"], cand, f["status_feature"])
    z_map = _raw_logits(cal.map, t["kd_bev_1"], cand, f["status_feature"])
    q_det, q_map = {}, {}
    for i, k in enumerate(CK_KEYS):
        pd_, pm = P_DET.get(k, {"a": 1.0, "b": 0.0}), P_MAP.get(k, {"a": 1.0, "b": 0.0})
        q_det[k] = torch.sigmoid(pd_["a"] * z_det[..., i] + pd_["b"])
        q_map[k] = torch.sigmoid(pm["a"] * z_map[..., i] + pm["b"])
        torch.testing.assert_close(o_cal["p_det"][..., i], q_det[k], rtol=1e-5, atol=1e-6)
        torch.testing.assert_close(o_cal["p_map"][..., i], q_map[k], rtol=1e-5, atol=1e-6)
    # combination AFTER calibration: nc / ttc DET, dac MAP, ep / comfort mean (comfort: both identity)
    want = {"nc": q_det["nc"], "dac": q_map["dac"], "ep": 0.5 * (q_det["ep"] + q_map["ep"]), "ttc": q_det["ttc"],
            "comfort": 0.5 * (q_det["comfort"] + q_map["comfort"])}
    for i, k in enumerate(CK_KEYS):
        torch.testing.assert_close(o_cal["kd_score_prob"][..., i], want[k], rtol=1e-5, atol=1e-6)
    # comfort (identity for both teachers) is bit-identical to the uncalibrated pair; the lateral side untouched
    j = CK_KEYS.index("comfort")
    assert torch.equal(o_cal["kd_score_prob"][..., j], o_raw["kd_score_prob"][..., j])
    for k in ("kd_e_lat", "e_det", "e_map", "kd_ok"):
        assert torch.equal(o_cal[k], o_raw[k]), k
    assert not torch.equal(o_cal["kd_score_prob"], o_raw["kd_score_prob"])
    # only MAP calibrated (det null): DET probabilities unchanged bitwise
    only_m = O.TeacherPair2(str(T), str(M), "last", "cpu", amp=False, calib={"det": None, "map": str(pM)})
    assert set(only_m.calib) == {"map"}
    o_m = only_m.run(*args)
    assert torch.equal(o_m["p_det"], o_raw["p_det"])
    torch.testing.assert_close(o_m["p_map"], o_cal["p_map"], rtol=0, atol=0)


